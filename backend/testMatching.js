tests.forEach(
  ([input, expected], index) => {
    const result =
      findSmartAnswer(
        input,
        answers
      );

    const actual =
      result
        ? result.rank
        : null;

    const success =
      actual === expected;

    if (success) {
      passed++;

      console.log(
        `✅ ${index + 1}. "${input}"`
      );

      if (result) {
        console.log(
          `   → ${result.answer}`
        );

        console.log(
          `   method: ${result.matchMethod}`
        );

        console.log(
          `   score: ${result.matchScore}`
        );
      } else {
        console.log(
          "   → مرفوض"
        );
      }
    } else {
      failed++;

      failures.push({
        input,
        expected,
        actual,

        matched:
          result
            ? result.answer
            : null,

        method:
          result
            ? result.matchMethod
            : null,

        score:
          result
            ? result.matchScore
            : null,
      });

      console.log(
        `❌ ${index + 1}. "${input}"`
      );

      console.log(
        `   expected: ${expected}`
      );

      console.log(
        `   actual: ${actual}`
      );

      if (result) {
        console.log(
          `   matched: ${result.answer}`
        );

        console.log(
          `   method: ${result.matchMethod}`
        );

        console.log(
          `   score: ${result.matchScore}`
        );
      }
    }

    console.log("");
  }
);

